// Real iCalendar (RFC 5545) generation + calendar deep links.
// The .ics download works in Apple Calendar, Google Calendar (import), Outlook and most other apps.

import type { SportEvent, Team, Venue } from "./types";

const pad = (n: number) => String(n).padStart(2, "0");

export function icsDate(iso: string) {
  const d = new Date(iso);
  return `${d.getUTCFullYear()}${pad(d.getUTCMonth() + 1)}${pad(d.getUTCDate())}T${pad(d.getUTCHours())}${pad(d.getUTCMinutes())}${pad(d.getUTCSeconds())}Z`;
}

export function escapeText(s: string) {
  return s.replace(/\\/g, "\\\\").replace(/;/g, "\\;").replace(/,/g, "\\,").replace(/\r?\n/g, "\\n");
}

/** Fold lines longer than 75 octets (RFC 5545 §3.1). */
export function fold(line: string) {
  const bytes = new TextEncoder().encode(line);
  if (bytes.length <= 75) return line;
  const out: string[] = [];
  let current = "";
  let size = 0;
  for (const ch of line) {
    const n = new TextEncoder().encode(ch).length;
    if (size + n > (out.length ? 74 : 75)) {
      out.push(current);
      current = "";
      size = 0;
    }
    current += ch;
    size += n;
  }
  out.push(current);
  return out.join("\r\n ");
}

export function buildICS(events: SportEvent[], ctx: { venues: Venue[]; teams: Team[] }, calName = "SportSync schedule", now = new Date()) {
  const lines = [
    "BEGIN:VCALENDAR",
    "VERSION:2.0",
    "PRODID:-//SportSync//Portfolio Prototype//EN",
    "CALSCALE:GREGORIAN",
    "METHOD:PUBLISH",
    `X-WR-CALNAME:${escapeText(calName)}`,
  ];
  for (const ev of events) {
    if (ev.status === "cancelled" && !ev.id) continue;
    const venue = ctx.venues.find((v) => v.id === ev.venueId);
    const teams = ev.teamIds.map((t) => ctx.teams.find((x) => x.id === t)?.name).filter(Boolean).join(", ");
    const desc = [`Type: ${ev.type}`, teams && `Teams: ${teams}`, ev.label, ev.notes, ev.statusReason && `Status note: ${ev.statusReason}`, "Generated by the SportSync portfolio prototype (sample data)."]
      .filter(Boolean)
      .join("\n");
    lines.push(
      "BEGIN:VEVENT",
      `UID:${ev.id}@sportsync.demo`,
      `DTSTAMP:${icsDate(now.toISOString())}`,
      `DTSTART:${icsDate(ev.start)}`,
      `DTEND:${icsDate(ev.end)}`,
      `SUMMARY:${escapeText((ev.status === "cancelled" ? "CANCELLED: " : ev.status === "postponed" ? "POSTPONED: " : "") + ev.title)}`,
      `LOCATION:${escapeText(venue ? `${venue.site} - ${venue.name}, ${venue.address}` : "TBD")}`,
      `DESCRIPTION:${escapeText(desc)}`,
      `STATUS:${ev.status === "cancelled" ? "CANCELLED" : ev.status === "postponed" ? "TENTATIVE" : "CONFIRMED"}`,
      `CATEGORIES:${ev.type.toUpperCase()}`,
      "BEGIN:VALARM",
      "TRIGGER:-PT1H",
      "ACTION:DISPLAY",
      `DESCRIPTION:${escapeText(ev.title)}`,
      "END:VALARM",
      "END:VEVENT",
    );
  }
  lines.push("END:VCALENDAR");
  return lines.map(fold).join("\r\n") + "\r\n";
}

export function googleCalendarUrl(ev: SportEvent, venue?: Venue) {
  const q = new URLSearchParams({
    action: "TEMPLATE",
    text: ev.title,
    dates: `${icsDate(ev.start)}/${icsDate(ev.end)}`,
    details: `${ev.type} · SportSync prototype (sample data)`,
    location: venue ? `${venue.site} - ${venue.name}, ${venue.address}` : "",
  });
  return `https://calendar.google.com/calendar/render?${q.toString()}`;
}

export function outlookCalendarUrl(ev: SportEvent, venue?: Venue) {
  const q = new URLSearchParams({
    path: "/calendar/action/compose",
    rru: "addevent",
    subject: ev.title,
    startdt: new Date(ev.start).toISOString(),
    enddt: new Date(ev.end).toISOString(),
    body: `${ev.type} · SportSync prototype (sample data)`,
    location: venue ? `${venue.site} - ${venue.name}, ${venue.address}` : "",
  });
  return `https://outlook.live.com/calendar/0/deeplink/compose?${q.toString()}`;
}

export function downloadText(filename: string, text: string, mime: string) {
  const blob = new Blob([text], { type: mime });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
